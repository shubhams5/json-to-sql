import { describe, expect, it } from "vitest";
import { getDialect, listDialects } from "./index.js";
import type { TableModel } from "../types.js";

const sampleTable: TableModel = {
  name: "users",
  originalName: "users",
  sourcePath: "$",
  primaryKey: ["id"],
  indexes: [{ id: "idx_users_email", name: "idx_users_email", columns: ["email"], unique: true }],
  foreignKeys: [],
  columns: [
    {
      name: "id",
      originalName: "id",
      inferredType: "integer",
      sqlType: "INTEGER",
      nullable: false,
      isPrimaryKey: true,
      isUnique: true,
      isExcluded: false,
      autoIncrement: true,
    },
    {
      name: "email",
      originalName: "email",
      inferredType: "string",
      sqlType: "TEXT",
      nullable: false,
      isPrimaryKey: false,
      isUnique: true,
      isExcluded: false,
    },
  ],
};

describe("dialects", () => {
  it("lists four dialects", () => {
    expect(listDialects().map((d) => d.value).sort()).toEqual(["mssql", "mysql", "postgres", "sqlite"]);
  });

  it.each(["postgres", "mysql", "mssql", "sqlite"] as const)("escapes identifiers for %s", (id) => {
    const dialect = getDialect(id);
    const quoted = dialect.quoteIdent('na"me');
    expect(quoted.includes("na")).toBe(true);
    expect(dialect.quoteLiteral("O'Reilly")).toContain("''");
  });

  it("creates deterministic create table SQL", () => {
    const sql = getDialect("postgres").createTable(sampleTable);
    expect(sql).toContain('CREATE TABLE "users"');
    expect(sql).toContain("PRIMARY KEY");
    expect(sql).toContain("GENERATED BY DEFAULT AS IDENTITY");
  });
});
