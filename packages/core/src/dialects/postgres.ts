import type { ColumnModel, InferredPrimitiveType } from "../types.js";
import { BaseDialect } from "./base.js";

export class PostgresDialect extends BaseDialect {
  id = "postgres" as const;
  label = "PostgreSQL";

  quoteIdent(name: string): string {
    return `"${name.replace(/"/g, '""')}"`;
  }

  mapType(inferred: InferredPrimitiveType): string {
    switch (inferred) {
      case "integer":
        return "INTEGER";
      case "number":
        return "DOUBLE PRECISION";
      case "boolean":
        return "BOOLEAN";
      case "json":
      case "object":
      case "array":
        return "JSONB";
      case "null":
      case "string":
      case "unknown":
      default:
        return "TEXT";
    }
  }

  autoIncrementClause(column: ColumnModel): string {
    if (column.inferredType === "integer" || column.sqlType.toUpperCase().includes("INT")) {
      return "GENERATED BY DEFAULT AS IDENTITY";
    }
    return "";
  }
}
